-- День 10. Транзакции и ACID
-- База: learn_sql, инструмент: psql (не DBeaver).
-- Приглашение: =# вне транзакции, =*# внутри, =!# транзакция сломана.

-- ACID:
--   A (atomicity)   : всё или ничего
--   C (consistency) : после транзакции правила базы (CHECK, NOT NULL, FK, UNIQUE) соблюдены
--   I (isolation)   : чужое неподтверждённое не видно
--   D (durability)  : после COMMIT данные на диске, при сбое не пропадут
-- Вне BEGIN каждая команда сама транзакция (автокоммит).

------------------------------------------------------------
-- Шаг 1. Подготовка
------------------------------------------------------------
CREATE TABLE accounts (
  id serial PRIMARY KEY,
  name text NOT NULL,
  balance numeric(10,2) NOT NULL CHECK (balance >= 0)
);

INSERT INTO accounts (name, balance) VALUES ('Аня', 1000), ('Борис', 500);

SELECT * FROM accounts;
-- Результат: Аня 1000.00, Борис 500.00
-- Вопрос: что будет при списании больше, чем есть? Ответ: сработает CHECK.
-- Уточнение: это согласованность (C); код ошибки CHECK 23514 (номер помнить не нужно).

------------------------------------------------------------
-- Шаг 2. ROLLBACK
------------------------------------------------------------
-- Предсказание: 900 после первого SELECT, 1000 после второго. Верно.
BEGIN;
UPDATE accounts SET balance = balance - 100 WHERE name = 'Аня';
SELECT * FROM accounts;   -- Аня 900.00 (транзакция видит свои изменения)
ROLLBACK;
SELECT * FROM accounts;   -- Аня 1000.00
-- Приглашение: =# -> =*# после BEGIN -> =# после ROLLBACK.
-- Заметка: без ORDER BY порядок строк не гарантирован (Борис оказался первым).

------------------------------------------------------------
-- Шаг 3. COMMIT, перевод 300 от Ани к Борису
------------------------------------------------------------
-- Предсказание: 700 и 800. Верно.
BEGIN;
UPDATE accounts SET balance = balance - 300 WHERE name = 'Аня';
UPDATE accounts SET balance = balance + 300 WHERE name = 'Борис';
COMMIT;
SELECT * FROM accounts ORDER BY id;   -- Аня 700.00, Борис 800.00 (сумма 1500)
-- ОШИБКА: на вопрос «сервер упал между двумя UPDATE» назвал durability.
-- Правильно: сбой ДО COMMIT -> откат -> атомарность (A).
-- Сбой ПОСЛЕ COMMIT -> данные на диске -> durability (D).

------------------------------------------------------------
-- Шаг 4. Ошибка внутри транзакции
------------------------------------------------------------
-- Предсказание: «ошибка и не даст выполнить транзакцию, значения как до».
-- Итог верный, но неточно: транзакция не закрылась сразу, а перешла в =!#.
BEGIN;
UPDATE accounts SET balance = balance - 100 WHERE name = 'Аня';     -- UPDATE 1
UPDATE accounts SET balance = balance - 5000 WHERE name = 'Борис';
-- ERROR: new row for relation "accounts" violates check constraint "accounts_balance_check"
-- Failing row contains (2, Борис, -4200.00)
-- Приглашение стало =!#
COMMIT;   -- psql ответил ROLLBACK: COMMIT сломанной транзакции откатывает всё
SELECT * FROM accounts ORDER BY id;   -- Аня 700.00, Борис 800.00
-- Вопрос «почему у Ани 700, а не 600»: ответил «другое висит в транзакции» (неточно).
-- Правильно: упала вторая команда, атомарность откатила и первую.

------------------------------------------------------------
-- Шаг 5. Сломанная транзакция
------------------------------------------------------------
-- Предсказание не прислал.
BEGIN;
UPDATE accounts SET balance = balance - 5000 WHERE name = 'Борис';   -- ERROR (CHECK)
SELECT * FROM accounts;
-- ERROR: current transaction is aborted, commands ignored until end of transaction block
ROLLBACK;
SELECT * FROM accounts;   -- Аня 700.00, Борис 800.00

------------------------------------------------------------
-- Шаг 6. Две сессии: изоляция
------------------------------------------------------------
-- Предсказание: «наверное 600». НЕВЕРНО.
-- Термин назвал «атомарность». НЕВЕРНО: это изоляция.
-- Терминал 1:
BEGIN;
UPDATE accounts SET balance = balance - 100 WHERE name = 'Аня';
SELECT * FROM accounts ORDER BY id;   -- терминал 1: Аня 600.00
-- Терминал 2:
SELECT * FROM accounts ORDER BY id;   -- терминал 2: Аня 700.00 (чужое неподтверждённое не видно)

------------------------------------------------------------
-- Шаг 7. COMMIT и вторая сессия
------------------------------------------------------------
-- Предсказание: 600. Верно (сначала прислал только слово commit, без вывода).
-- Терминал 1:
COMMIT;
-- Терминал 2:
SELECT * FROM accounts ORDER BY id;   -- Аня 600.00, Борис 800.00 (сумма 1400)

------------------------------------------------------------
-- Шаг 8. Конфликт на одной строке: блокировка
------------------------------------------------------------
-- Предсказание: «либо зависнет, либо ошибка» (это не предсказание: выбрать один вариант).
-- Ожидаемое поведение: второй UPDATE ждёт COMMIT (что именно видел терминал 2, не описал).
-- Терминал 1:
BEGIN;
UPDATE accounts SET balance = balance - 50 WHERE name = 'Аня';
-- Терминал 2:
UPDATE accounts SET balance = balance - 50 WHERE name = 'Аня';
-- Терминал 1:
COMMIT;
SELECT * FROM accounts ORDER BY id;   -- Аня 500.00 (600 - 50 - 50), Борис 800.00
-- ОШИБКА: назвал «изоляция». Правильно: блокировка строки (row lock).
-- Первое списание дало 550, второй UPDATE взял 550 и вычел 50, итог 500.
-- Без блокировки оба могли прочитать 600 и записать 550: списание потерялось бы.
-- Итоговый ответ: ждал, потому что транзакция не закрыта и строка заблокирована (верно).

------------------------------------------------------------
-- Уборка
------------------------------------------------------------
DROP TABLE accounts;
\dt
-- Остались: orders, users.

------------------------------------------------------------
-- Итоги и слабые места
------------------------------------------------------------
-- До COMMIT сбой  -> данные прежние -> атомарность.
-- После COMMIT сбой -> данные новые, на диске -> durability.
-- Ошибка внутри транзакции -> =!#, нужен ROLLBACK, откатывается всё -> атомарность.
-- SELECT чужого неподтверждённого -> старое значение -> изоляция.
-- После чужого COMMIT -> новое значение (изменение подтверждено).
-- UPDATE чужой неподтверждённой строки -> ждёшь -> блокировка строки.
-- Мини-проверка: верно 3, 4, частично 6; ошибки в 1, 2, 5 (перепутал сбой до/после COMMIT,
-- изоляцию и блокировку). Повторная проверка: верно 1, 2, 3б, ошибся в 3а (чтение чужого
-- неподтверждённого), потом исправил.
